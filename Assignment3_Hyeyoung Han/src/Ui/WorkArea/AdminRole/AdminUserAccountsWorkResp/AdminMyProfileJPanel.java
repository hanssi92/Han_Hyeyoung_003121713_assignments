    private void setViewMode() {
        editMode = false;
        
        txtAPLastActivity.setEnabled(false);
        txtAPLastUpdated.setEditable(false);
        txtAPUserName.setEnabled(false);
        txtAPRole.setEnabled(false);
        
        txtAPPassword.setEnabled(false);
        txtAPStatus.setEnabled(false);

        btnAPUpdate.setText("Update");
}

    private void setEditMode() {
        editMode = true;

    // 수정 가능한 것만 열기
        txtAPPassword.setEnabled(true);
        txtAPStatus.setEnabled(true);

        btnAPUpdate.setText("Save");
    }


