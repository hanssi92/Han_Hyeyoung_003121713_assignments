    private void btnAPUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAPUpdateActionPerformed
        // TODO add your handling code here:
        if (!editMode) {
            setEditMode();
            return;
        }
        String pw = txtAPPassword.getText();
        String status = txtAPStatus.getText();
        
        if(pw.isEmpty() || status.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill out all fields", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        userAccount.setPassword(pw);
        userAccount.setStatus(editMode);
        userAccount.setLastActivity(java.time.LocalDateTime.now().toString());
        userAccount.setLastUpdated(java.time.LocalDateTime.now().toString());
        
        JOptionPane.showMessageDialog(this, "Successfully updated", "Information", JOptionPane.INFORMATION_MESSAGE);
        
        populateFields();
        setViewMode();
 
    }//GEN-LAST:event_btnAPUpdateActionPerformed


